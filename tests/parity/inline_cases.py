"""
Write the `recorded/inline/` recording sets: the pages and payloads the Python
tests build inline, as files in the recorded-HTTP format.

    python tests/parity/inline_cases.py [--out DIR]

The case definitions live in `cases_providers`, `cases_tmdb` and
`cases_reconcile`. The output is committed; `tests/test_parity_golden.py`
fails if it drifts from these definitions.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tests.parity.common import RECORDED  # noqa: E402

HTML = "text/html; charset=utf-8"
JSON = "application/json; charset=utf-8"


@dataclass
class Response:
    body: str
    status: int = 200
    content_type: str = HTML


@dataclass
class Case:
    """One inline recording set: what the provider (or enricher) is served, and what it is asked to do."""

    kind: str  # english_cinema_bcn | secondary | verdi | sensacine | tmdb | tmdb-rank | reconcile
    name: str
    description: str
    source: list[str]  # the Python tests this case was drawn from
    now: str  # the frozen instant, ISO 8601 with offset
    responses: dict[str, Response] = field(default_factory=dict)
    fields: dict[str, Any] = field(default_factory=dict)  # the rest of case.json

    def page(self, url: str, body: str, status: int = 200) -> Case:
        self.responses[url] = Response(body, status, HTML)
        return self

    def payload(self, url: str, body: object, status: int = 200) -> Case:
        self.responses[url] = Response(json.dumps(body, indent=2, ensure_ascii=False) + "\n", status, JSON)
        return self


def _file_name(index: int, url: str, content_type: str) -> str:
    parts = urlsplit(url)
    stem = re.sub(r"[^A-Za-z0-9]+", "-", f"{parts.hostname}{parts.path}{'-' + parts.query if parts.query else ''}")
    extension = "json" if "json" in content_type else "html"
    return f"{index:02d}-{stem.strip('-')[:80]}.{extension}"


def _write(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def write_case(root: Path, case: Case) -> None:
    directory = root / case.kind / case.name
    manifest = []
    for index, (url, response) in enumerate(case.responses.items(), start=1):
        file_name = _file_name(index, url, response.content_type)
        (directory / file_name).parent.mkdir(parents=True, exist_ok=True)
        (directory / file_name).write_text(response.body, encoding="utf-8")
        manifest.append(
            {
                "method": "GET",
                "url": url,
                "status": response.status,
                "contentType": response.content_type,
                "file": file_name,
            }
        )
    _write(directory / "manifest.json", manifest)
    _write(
        directory / "case.json",
        {"description": case.description, "source": _sources(case), "now": case.now, **case.fields},
    )


def _sources(case: Case) -> list[str]:
    """`source` with a leading "::name" read as a test in the file of the first entry."""
    file = case.source[0].split("::", 1)[0]
    return [f"{file}{entry}" if entry.startswith("::") else entry for entry in case.source]


_README_HEAD = """\
# Inline recordings

Pages and payloads the legacy Python tests build inline, as recording sets in
the recorded-HTTP format, with the Python output in `../../goldens/inline/`.
Generated by `python tests/parity/inline_cases.py`; do not edit by hand.

Layout: `<kind>/<case>/` holds `manifest.json` (an array of
`{method, url, status, contentType, file}`; match `url` exactly), the body
files, and `case.json`. `case.json` has `description`, `source`, `now` (the
frozen instant) and, by kind:

- `english_cinema_bcn`, `secondary`: `config.listingsFeedUrl` / `config.secondaryListingsUrl`
  (the secret URLs, replaced by `*.example.test` stand-ins).
- `verdi`: optional `salaMap` ({session id: cinema key}, the cached map the provider is seeded with).
- `sensacine`: `sensacine.ids` (cinema key to theatre id, in order) and
  `sensacine.daysAhead`: the theatres and days the provider is narrowed to.
- `tmdb`: `movies` (input to enrichment), optional `cached` (previous refresh's movies),
  optional `reconcileFirst` (reconcile `movies` at stage "collection" first).
- `tmdb-rank`: `title`, `results`, optional `year`, `today`; or `details` (first-run window cases).
- `reconcile`: `movies`, optional `stage`.

All cases use the repo's `cinemas.json` (snapshot: `../../cinemas.json`).
TMDb URLs are stored without the credential parameter, the others in request order.

Goldens (`../../goldens/inline/<kind>/<case>.json`): provider kinds and `tmdb`/`reconcile`
are objects with `result` (or `error` `{type, message}`), `requests` (URLs asked for; sorted
except for `tmdb`, where the order is the behavior) and `events` (structured log events);
`tmdb` has `enriched`, `reconciled`, `stats`, `requests`, `events` instead of `result`.
`tmdb-matches.json` lists the chosen TMDb film per listed title, per case.

Live sets (`../live-<date>/`, from `tests/parity/record.py`) use the same manifest
format; their `case.json` has `now`, `sensacine.{ids,daysAhead}` and `verdi.slugs`
(the film pages the provider is narrowed to; the cartellera body is stored whole).
Their goldens are plain arrays: `verdi.json`, `sensacine.json`, `reconciled.json`
(`reconcile(verdi + sensacine, stage="collection")`), and `sensacine-by-version/<key>.json`:
the SensaCine fetch with each page's `<key>` showtimes filed under `original` and the other
versions removed, one file per version key that has showtimes.

## Cases and the Python tests they come from
"""


def _readme(cases: list[Case]) -> str:
    lines = [_README_HEAD]
    for case in sorted(cases, key=lambda c: (c.kind, c.name)):
        by_file: dict[str, list[str]] = {}
        for source in _sources(case):
            file, _, test = source.partition("::")
            by_file.setdefault(file.removeprefix("tests/"), []).append(test)
        lines.append(f"- `{case.kind}/{case.name}`: " + "; ".join(f"{f} ({', '.join(t)})" for f, t in by_file.items()))
    return "\n".join(lines) + "\n"


def all_cases() -> list[Case]:
    from tests.parity import cases_providers, cases_reconcile, cases_tmdb

    return [*cases_providers.cases(), *cases_tmdb.cases(), *cases_reconcile.cases()]


def generate(out: Path) -> None:
    inline = out / "inline"
    for kind_dir in inline.glob("*/"):
        shutil.rmtree(kind_dir)
    names = set()
    cases = all_cases()
    for case in cases:
        if (case.kind, case.name) in names:
            raise ValueError(f"duplicate case {case.kind}/{case.name}")
        names.add((case.kind, case.name))
        write_case(inline, case)
    (inline / "README.md").write_text(_readme(cases), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=RECORDED, help="directory to write inline/ into")
    generate(parser.parse_args().out)


if __name__ == "__main__":
    main()
